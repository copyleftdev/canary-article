from lab import runner


def evaluation(task="reschedule"):
    return {"schema_version": 1, "task": task, "status": "completed",
            "build": "pass", "baseline_rules": "pass", "new_rules": "pass",
            "rules": "pass", "feature": "pass", "checks": [], "errors": []}


class RunnerEvidenceTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="canary-runner-test-")
        self.addCleanup(self.temporary.cleanup)
        self.base = Path(self.temporary.name)
        self.root = self.base / "project"
        sources = {
            "lab/runner.py": b"# controller fixture\n",
            "evaluator/evaluate.py": b"# evaluator fixture\n",
            "fixtures/baseline/booking.py": b"# booking fixture\n",
            "fixtures/baseline/AGENTS.md": b"Follow the contract.\n",
            "tasks/reschedule.txt": b"Reschedule a booking.\n",
            "docs/contract.md": "# Contract\nUTC café\n".encode(),
            "docs/experiment.md": b"# Protocol\n",
            "Dockerfile": b"# pinned runtime\n",
            "lab/__pycache__/ignored.pyc": b"ignored generated bytes",
        }
        for relative, content in sources.items():
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        self.binary = self.base / "codex"
        self.binary.write_bytes(b"fake binary for a content hash")
        self.runtime = {"codex_binary": str(self.binary), "codex_sha256": runner.sha(self.binary),
                        "codex_version": "test-only", "image_id": "sha256:test-image",
                        "filesystem_isolation": "pass", "probe_workspace_write": True}
        self.enterContext(patch.object(runner, "ROOT", self.root))
        self.doctor = self.enterContext(patch.object(runner, "doctor", return_value=self.runtime))
        # Any unexpected call to Docker, the CLI, or a subprocess must fail this test.
        self.enterContext(patch.object(runner, "command", side_effect=AssertionError("unexpected process call")))

    def plan(self, name="pilot", phase="pilot", pilot=None, seed=42, **overrides):
        options = {"output": self.base / name, "phase": phase, "binary": str(self.binary),
                   "image": "test-image", "model": "test-model", "effort": "high",
                   "timeout": 60, "seed": seed, "pilot": pilot}
        options.update(overrides)
        return runner.make_plan(**options)

    def completed_pilot(self):
        plan = self.plan()
        pilot = self.base / "pilot"
        for row in plan["runs"]:
            folder = pilot / "runs" / row["run_id"]
            result = {**row, "phase": "pilot", "termination": "completed",
                      "evaluation": evaluation(row["task"]),
                      "marker": {"status": "exact" if row["condition"] == "B" else "not_applicable"},
                      "final_response_observed": True, "event_parse_errors": 0}
            runner.write_json(folder / "result.json", result)
            (folder / "final.txt").write_text("A recorded final response.\n")
        return pilot, plan

    def calibration(self, hashes, status="pass"):
        runner.write_json(self.root / "artifacts/calibration/summary.json",
                          {"status": status, "source_hashes": hashes})

    def test_pilot_has_unique_adjacent_ab_blocks_and_independent_tokens(self):
        plan = self.plan()
        rows = plan["runs"]
        self.assertEqual(len(rows), 6)
        self.assertFalse(plan["frozen"])
        self.assertEqual(len({row["run_id"] for row in rows}), 6)
        self.assertEqual({row["task"] for row in rows}, set(runner.TASKS))
        for index in range(0, len(rows), 2):
            pair = rows[index:index + 2]
            self.assertEqual(pair[0]["block"], pair[1]["block"])
            self.assertEqual({row["condition"] for row in pair}, {"A", "B"})
        tokens = []
        for row in rows:
            if row["condition"] == "B":
                self.assertRegex(row["token"], r"^[0-9a-f]{16}$")
                tokens.append(row["token"])
            else:
                self.assertIsNone(row["token"])
        self.assertEqual(len(tokens), len(set(tokens)))

    def test_seed_reproduces_schedule_without_reusing_tokens(self):
        first = self.plan("first", seed=42)
        repeat = self.plan("repeat", seed=42)
        changed = self.plan("changed", seed=43)
        ids = lambda plan: [row["run_id"] for row in plan["runs"]]
        self.assertEqual(ids(first), ids(repeat))
        self.assertNotEqual(ids(first), ids(changed))
        self.assertNotEqual([row["token"] for row in first["runs"] if row["token"]],
                            [row["token"] for row in repeat["runs"] if row["token"]])

    def test_source_archive_preserves_exact_hashed_bytes(self):
        plan = self.plan()
        self.assertNotIn("lab/__pycache__/ignored.pyc", plan["source_hashes"])
        archive = self.base / "pilot/source"
        files = {str(path.relative_to(archive)) for path in archive.rglob("*") if path.is_file()}
        self.assertEqual(files, set(plan["source_hashes"]))
        for relative, digest in plan["source_hashes"].items():
            with self.subTest(relative=relative):
                content = (archive / relative).read_bytes()
                self.assertEqual(content, (self.root / relative).read_bytes())
                self.assertEqual(hashlib.sha256(content).hexdigest(), digest)
        self.assertEqual((self.base / "pilot/protocol.md").read_bytes(),
                         (self.root / "docs/experiment.md").read_bytes())

    def test_existing_cohort_cannot_be_overwritten(self):
        self.plan()
        before = (self.base / "pilot/plan.json").read_bytes()
        with self.assertRaisesRegex(FileExistsError, "Cohort directory already exists"):
            self.plan()
        self.assertEqual((self.base / "pilot/plan.json").read_bytes(), before)

    def test_main_cannot_freeze_without_pilot(self):
        with self.assertRaises(ValueError):
            self.plan("main", "main")
        self.assertFalse((self.base / "main").exists())

    def test_main_rejects_incomplete_pilot_plan(self):
        pilot, plan = self.completed_pilot()
        plan["runs"].pop()
        runner.write_json(pilot / "plan.json", plan)
        self.calibration(plan["source_hashes"])
        with self.assertRaises(ValueError):
            self.plan("main", "main", pilot)

    def test_main_rejects_failed_pilot_and_missing_result(self):
        pilot, plan = self.completed_pilot()
        self.calibration(plan["source_hashes"])
        path = pilot / "runs" / plan["runs"][0]["run_id"] / "result.json"
        result = json.loads(path.read_text())
        result["termination"] = "timeout"
        runner.write_json(path, result)
        with self.assertRaises(ValueError):
            self.plan("failed-main", "main", pilot)
        path.unlink()
        with self.assertRaises((FileNotFoundError, ValueError)):
            self.plan("missing-main", "main", pilot)

    def test_main_requires_matching_successful_calibration(self):
        pilot, plan = self.completed_pilot()
        with self.assertRaises((FileNotFoundError, ValueError)):
            self.plan("missing-calibration", "main", pilot)
        self.calibration(plan["source_hashes"], status="fail")
        with self.assertRaises(ValueError):
            self.plan("failed-calibration", "main", pilot)
        self.calibration({"unrelated": "hash"})
        with self.assertRaises(ValueError):
            self.plan("stale-calibration", "main", pilot)

    def test_main_rejects_unobserved_final_or_parser_errors(self):
        pilot, plan = self.completed_pilot()
        self.calibration(plan["source_hashes"])
        path = pilot / "runs" / plan["runs"][0]["run_id"] / "result.json"
        original = json.loads(path.read_text())
        for name, changes in (("no-final", {"final_response_observed": False}),
                               ("parse-errors", {"event_parse_errors": 1})):
            with self.subTest(case=name):
                runner.write_json(path, {**original, **changes})
                with self.assertRaisesRegex(ValueError, "terminal-response"):
                    self.plan(name, "main", pilot)

    def test_main_rejects_runtime_or_source_drift(self):
        pilot, plan = self.completed_pilot()
        self.calibration(plan["source_hashes"])
        with self.assertRaisesRegex(ValueError, "Main runtime differs from pilot: model"):
            self.plan("changed-model", "main", pilot, model="another-model")
        with self.assertRaisesRegex(ValueError, "Main runtime differs from pilot: timeout_seconds"):
            self.plan("changed-budget", "main", pilot, timeout=61)
        (self.root / "tasks/reschedule.txt").write_text("A changed prompt.\n")
        with self.assertRaisesRegex(ValueError, "Sources changed since pilot"):
            self.plan("changed-sources", "main", pilot)

    def test_main_contains_exactly_thirty_attempts_with_fifteen_paired_blocks(self):
        pilot, previous = self.completed_pilot()
        self.calibration(previous["source_hashes"])
        plan = self.plan("main", "main", pilot)
        self.assertTrue(plan["frozen"])
        rows = plan["runs"]
        self.assertEqual(len(rows), 30)
        self.assertEqual(len({row["run_id"] for row in rows}), 30)
        for task in runner.TASKS:
            for condition in ("A", "B"):
                self.assertEqual(sum(row["task"] == task and row["condition"] == condition for row in rows), 5)
        for index in range(0, 30, 2):
            self.assertEqual(rows[index]["block"], rows[index + 1]["block"])
            self.assertEqual({rows[index]["condition"], rows[index + 1]["condition"]}, {"A", "B"})

    def test_condition_c_is_length_matched_and_requests_no_marker(self):
        token = "0123456789abcdef"
        marker = runner.marker_instruction(token)
        neutral = runner.NEUTRAL_INSTRUCTION
        self.assertLessEqual(abs(len(neutral) - len(marker)) / len(marker), 0.05)
        self.assertNotIn("CANARY", neutral)
        self.assertNotIn("final response", neutral)
        base = "Rules.\n"
        self.assertEqual(runner.build_instructions(base, "A", None), base)
        self.assertEqual(runner.build_instructions(base, "B", token), base + marker)
        self.assertEqual(runner.build_instructions(base, "C", None), base + neutral)

    def test_abc_pilot_and_main_use_triple_blocks(self):
        plan = self.plan(conditions="ABC")
        self.assertEqual(plan["conditions"], ["A", "B", "C"])
        self.assertEqual(len(plan["runs"]), 9)
        for index in range(0, 9, 3):
            block = plan["runs"][index:index + 3]
            self.assertEqual(len({row["block"] for row in block}), 1)
            self.assertEqual({row["condition"] for row in block}, {"A", "B", "C"})
        for row in plan["runs"]:
            self.assertEqual(row["token"] is not None, row["condition"] == "B")
        pilot = self.base / "pilot"
        for row in plan["runs"]:
            folder = pilot / "runs" / row["run_id"]
            runner.write_json(folder / "result.json", {
                **row, "phase": "pilot", "termination": "completed", "evaluation": evaluation(row["task"]),
                "final_response_observed": True, "event_parse_errors": 0})
        self.calibration(plan["source_hashes"])
        with self.assertRaisesRegex(ValueError, "same conditions"):
            self.plan("main-ab", "main", pilot)
        main = self.plan("main", "main", pilot, conditions="ABC")
        self.assertEqual(len(main["runs"]), 45)
        for task in runner.TASKS:
            for condition in "ABC":
                self.assertEqual(sum(r["task"] == task and r["condition"] == condition for r in main["runs"]), 5)

