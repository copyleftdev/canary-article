    def test_replay_rejects_redacted_implementation(self):
        _, row, snapshot = self.save_snapshot()
        result_path = snapshot.parent / "result.json"
        result = json.loads(result_path.read_text())
        result["snapshot_redacted_paths"] = ["booking.py"]
